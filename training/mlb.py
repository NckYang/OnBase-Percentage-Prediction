def apply_calibration(probabilities):
    probabilities = np.clip(np.asarray(probabilities), 1e-6, 1 - 1e-6)
    logits = np.log(probabilities / (1 - probabilities)).reshape(-1, 1)
    return calibrator.predict_proba(logits)[:, 1]


def weighted_calibration_table(y_true, probabilities, weights, n_bins=10):
    frame = pd.DataFrame({
        'actual': np.asarray(y_true), 'predicted': probabilities,
        'weight': np.asarray(weights),
    })
    frame['bin'] = pd.cut(
        frame['predicted'], bins=np.linspace(0, 1, n_bins + 1),
        include_lowest=True, labels=False
    )
    rows = []
    for bin_id, group in frame.groupby('bin', observed=True):
        total_weight = group['weight'].sum()
        rows.append({
            'bin': int(bin_id),
            'mean_predicted': np.average(group['predicted'], weights=group['weight']),
            'actual_rate': np.average(group['actual'], weights=group['weight']),
            'weight': total_weight,
        })
    return pd.DataFrame(rows)

