def build_recent_and_outcome_features(current_pa, previous_pa):
    """依打席時間順序建立近期與事件拆分特徵，當前打席永遠先 shift。"""
    combined = pd.concat([previous_pa, current_pa], ignore_index=True)
    combined = combined.sort_values(
        ['game_date', 'game_pk', 'at_bat_number']
    ).reset_index(drop=True)
    combined['is_hit'] = combined['events'].isin(HIT_EVENTS).astype('int8')
    combined['is_walk'] = combined['events'].isin(WALK_EVENTS).astype('int8')
    combined['is_strikeout'] = combined['events'].isin(STRIKEOUT_EVENTS).astype('int8')
    combined['pa_woba'] = combined['woba_value'].fillna(0).clip(0, 2)
    combined['pa_xwoba'] = combined['estimated_woba_using_speedangle'].fillna(
        combined['woba_value']
    ).fillna(0).clip(0, 2)

    for entity, entity_col in [('batter', 'batter'), ('pitcher', 'pitcher')]:
        grouped = combined.groupby(entity_col, sort=False)
        prior_count = grouped.cumcount()
        for outcome in ['is_hit', 'is_walk', 'is_strikeout']:
            prior_success = grouped[outcome].cumsum() - combined[outcome]
            combined[f'{entity}_hist_{outcome[3:]}_rate'] = (
                prior_success + OUTCOME_PRIORS[outcome] * PLAYER_PRIOR_PA
            ) / (prior_count + PLAYER_PRIOR_PA)
        for metric in ['pa_woba', 'pa_xwoba']:
            prior_total = grouped[metric].cumsum() - combined[metric]
            combined[f'{entity}_hist_{metric[3:]}'] = (
                prior_total + 0.315 * PLAYER_PRIOR_PA
            ) / (prior_count + PLAYER_PRIOR_PA)

        for window in [50, 100]:
            rolled = (
                grouped['is_obp_success'].rolling(window, min_periods=1).sum()
                .reset_index(level=0, drop=True)
            )
            prior_rolled = rolled.groupby(combined[entity_col], sort=False).shift(1)
            recent_samples = prior_count.clip(upper=window)
            combined[f'{entity}_recent_{window}_obp'] = (
                prior_rolled.fillna(0) + LEAGUE_PRIOR_OBP * RECENT_PRIOR_PA
            ) / (recent_samples + RECENT_PRIOR_PA)
            combined[f'{entity}_recent_{window}_log_samples'] = np.log1p(recent_samples)

    current_keys = set(map(tuple, current_pa[['game_pk', 'at_bat_number']].to_numpy()))
    mask = combined[['game_pk', 'at_bat_number']].apply(tuple, axis=1).isin(current_keys)
    feature_cols = [
        column for column in combined.columns
        if '_hist_' in column or '_recent_' in column
    ]
    return combined.loc[mask, ['game_pk', 'at_bat_number', *feature_cols]]


def build_pitch_profile_features(current_pitches, previous_pitches):
    """建立投手球種傾向、打者對球種反應與 Whiff/Chase 歷史特徵。"""
    current = current_pitches.copy()
    current['_is_current'] = 1
    previous = previous_pitches.copy()
    previous['_is_current'] = 0
    combined = pd.concat([previous, current], ignore_index=True).sort_values(
        ['game_date', 'game_pk', 'at_bat_number', 'pitch_number']
    ).reset_index(drop=True)
    combined['pitch_family'] = combined['pitch_type'].map(PITCH_FAMILY).fillna('other')
    combined['is_swing'] = combined['description'].isin(SWING_DESCRIPTIONS).astype('int8')
    combined['is_whiff'] = combined['description'].isin(WHIFF_DESCRIPTIONS).astype('int8')
    combined['is_outside_zone'] = (
        combined['zone'].notna() & ~combined['zone'].between(1, 9)
    ).astype('int8')
    combined['is_chase'] = (combined['is_swing'] & combined['is_outside_zone']).astype('int8')

    for entity in ['batter', 'pitcher']:
        grouped = combined.groupby(entity, sort=False)
        prior_pitches = grouped.cumcount()
        for outcome, prior in [('whiff', 0.105), ('chase', 0.280)]:
            values = combined[f'is_{outcome}']
            prior_sum = grouped[f'is_{outcome}'].cumsum() - values
            combined[f'{entity}_hist_{outcome}_rate'] = (
                prior_sum + prior * 100
            ) / (prior_pitches + 100)

    pitcher_group = combined.groupby('pitcher', sort=False)
    pitcher_prior_count = pitcher_group.cumcount()
    for family in PITCH_FAMILIES:
        family_flag = combined['pitch_family'].eq(family).astype('int8')
        family_prior = family_flag.groupby(combined['pitcher'], sort=False).cumsum() - family_flag
        combined[f'pitcher_{family}_usage'] = (
            family_prior + 0.25 * 50
        ) / (pitcher_prior_count + 50)

        batter_family_count = family_flag.groupby(combined['batter'], sort=False).cumsum() - family_flag
        family_whiff = (family_flag & combined['is_whiff']).astype('int8')
        batter_family_whiff = (
            family_whiff.groupby(combined['batter'], sort=False).cumsum() - family_whiff
        )
        combined[f'batter_{family}_whiff_rate'] = (
            batter_family_whiff + 0.105 * 30
        ) / (batter_family_count + 30)

    combined['expected_matchup_whiff_rate'] = sum(
        combined[f'pitcher_{family}_usage']
        * combined[f'batter_{family}_whiff_rate']
        for family in PITCH_FAMILIES
    )
    feature_cols = [
        'batter_hist_whiff_rate', 'batter_hist_chase_rate',
        'pitcher_hist_whiff_rate', 'pitcher_hist_chase_rate',
        'expected_matchup_whiff_rate',
        *[f'pitcher_{family}_usage' for family in PITCH_FAMILIES],
        *[f'batter_{family}_whiff_rate' for family in PITCH_FAMILIES],
    ]
    return combined.loc[combined['_is_current'].eq(1), feature_cols].reset_index(drop=True)


def build_smoothed_history(pa_results, group_cols, success_totals, count_totals,
                           feature_prefix, prior_strength):
    """建立只使用當日以前資料的平滑歷史率，並跨年度延續累積值。"""
    stats = (
        pa_results.groupby(['game_date', *group_cols], dropna=False)['is_obp_success']
        .agg(['sum', 'count']).reset_index()
        .sort_values([*group_cols, 'game_date'])
    )
    keys = list(map(tuple, stats[group_cols].itertuples(index=False, name=None)))
    stats['_key'] = keys
    stats['_prior_success'] = stats['_key'].map(success_totals).fillna(0)
    stats['_prior_count'] = stats['_key'].map(count_totals).fillna(0)
    grouped = stats.groupby(group_cols, dropna=False)
    stats[f'{feature_prefix}_successes'] = (
        stats['_prior_success'] + grouped['sum'].cumsum() - stats['sum']
    )
    stats[f'{feature_prefix}_samples'] = (
        stats['_prior_count'] + grouped['count'].cumsum() - stats['count']
    )
    stats[f'{feature_prefix}_rate'] = (
        stats[f'{feature_prefix}_successes'] + LEAGUE_PRIOR_OBP * prior_strength
    ) / (stats[f'{feature_prefix}_samples'] + prior_strength)

    totals = stats.groupby('_key')[['sum', 'count']].sum()
    for key, row in totals.iterrows():
        success_totals[key] = success_totals.get(key, 0) + int(row['sum'])
        count_totals[key] = count_totals.get(key, 0) + int(row['count'])

    keep = ['game_date', *group_cols, f'{feature_prefix}_rate', f'{feature_prefix}_samples']
    return stats[keep]

